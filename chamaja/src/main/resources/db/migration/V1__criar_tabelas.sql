-- Chama Já: tabelas iniciais do MVP.
-- Roda no schema "chamaja" (spring.flyway.default-schema); por isso nada aqui leva prefixo.

create table estabelecimento (
    id            bigint generated by default as identity primary key,
    nome          varchar(100) not null,
    codigo_qr     varchar(40)  not null,
    estado_fila   varchar(10)  not null,
    senha_atual   integer      not null,
    ultimo_numero integer      not null,
    constraint uk_estabelecimento_codigo_qr unique (codigo_qr),
    constraint ck_estabelecimento_estado_fila check (estado_fila in ('ABERTA', 'PAUSADA', 'FECHADA'))
);

create table operador (
    id                 bigint generated by default as identity primary key,
    estabelecimento_id bigint      not null references estabelecimento (id),
    usuario            varchar(50) not null,
    senha_hash         varchar(100) not null,
    constraint uk_operador_usuario unique (usuario)
);
create index idx_operador_estabelecimento on operador (estabelecimento_id);

create table senha (
    id                        bigint generated by default as identity primary key,
    estabelecimento_id        bigint       not null references estabelecimento (id),
    token                     varchar(36)  not null,
    numero                    integer      not null,
    nome_cliente              varchar(60)  not null,
    status                    varchar(12)  not null,
    entrada                   timestamp(6) with time zone not null,
    chamada_em                timestamp(6) with time zone,
    aviso_proximidade_enviado boolean      not null,
    constraint uk_senha_token unique (token),
    constraint ck_senha_status check (status in ('AGUARDANDO', 'CHAMADA', 'FINALIZADA', 'PULADA', 'CANCELADA'))
);
-- Posição na fila e "próxima a chamar" consultam por estabelecimento + status + número.
create index idx_senha_estab_status_numero on senha (estabelecimento_id, status, numero);

create table promocao (
    id                 bigint generated by default as identity primary key,
    estabelecimento_id bigint        not null references estabelecimento (id),
    titulo             varchar(100)  not null,
    descricao          varchar(500),
    preco              numeric(10,2) not null,
    validade           date          not null,
    ativa              boolean       not null
);
create index idx_promocao_estabelecimento on promocao (estabelecimento_id);

-- Defesa em profundidade para o Supabase: com RLS ligado e sem nenhuma política, os papéis da API
-- pública (anon e authenticated) não leem nem escrevem nada. A aplicação conecta como dono das
-- tabelas, que não é afetado pelo RLS.
alter table estabelecimento enable row level security;
alter table operador        enable row level security;
alter table senha           enable row level security;
alter table promocao        enable row level security;

-- Esses papéis só existem no Supabase; num PostgreSQL comum o bloco é ignorado.
do $$
begin
    if exists (select 1 from pg_roles where rolname = 'anon')
       and exists (select 1 from pg_roles where rolname = 'authenticated') then
        execute format('revoke all on schema %I from anon, authenticated', current_schema());
        execute format('revoke all on all tables in schema %I from anon, authenticated', current_schema());
        execute format('revoke all on all sequences in schema %I from anon, authenticated', current_schema());
    end if;
end
$$;
