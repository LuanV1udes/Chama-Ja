-- Web Push: avisos no celular (tela bloqueada). Cada senha pode ter UMA inscrição de push, que é
-- apagada junto com a senha (fim do dia, "zerar fila", senha encerrada).

create table inscricao_push (
    id        bigint generated by default as identity primary key,
    senha_id  bigint        not null references senha (id) on delete cascade,
    endpoint  varchar(1000) not null,
    p256dh    varchar(255)  not null,
    auth      varchar(100)  not null,
    criada_em timestamp(6) with time zone not null,
    constraint uk_inscricao_push_endpoint unique (endpoint),
    constraint uk_inscricao_push_senha unique (senha_id)
);

-- Já avisamos por push que a vez está chegando (faltam até 3 números)? Evita repetir o aviso.
alter table senha add column push_proximidade_enviado boolean not null default false;

-- O endpoint e as chaves identificam o aparelho do cliente: ficam fora da API pública do Supabase.
alter table inscricao_push enable row level security;
do $$
begin
    if exists (select 1 from pg_roles where rolname = 'anon')
       and exists (select 1 from pg_roles where rolname = 'authenticated') then
        execute format('revoke all on table inscricao_push from anon, authenticated');
    end if;
end
$$;
